// ---------------------------------------------------------------------------------------------
// Rust core: usos-ffi is built by Gradle itself (cargo-ndk), as F-Droid needs, and its Kotlin
// bindings are generated by uniffi-bindgen in library mode. Both run inside the `android` toolbox
// after `source ~/Android/env.sh` (JAVA_HOME, ANDROID_NDK_HOME, RUSTUP_HOME, CARGO_HOME).
//
// Per variant: debug uses cargo's dev profile, release uses `--release`. ABIs: debug builds
// x86_64 only, release builds arm64-v8a, armeabi-v7a and x86_64; -Plibreusos.abis=a,b overrides both
// (gradle.properties does not set it).
// ---------------------------------------------------------------------------------------------

val minSdkVersion = 26
val pinnedNdkVersion = "28.2.13676358"

// cargo-ndk ABI name -> Rust target triple.
val abiToTriple = mapOf(
    "x86_64" to "x86_64-linux-android",
    "arm64-v8a" to "aarch64-linux-android",
    "armeabi-v7a" to "armv7-linux-androideabi",
    "x86" to "i686-linux-android",
)

fun abisFor(release: Boolean): List<String> {
    val override = providers.gradleProperty("libreusos.abis").orNull
    val abis = override?.split(',')?.map { it.trim() }?.filter { it.isNotEmpty() }
        ?: if (release) listOf("arm64-v8a", "armeabi-v7a", "x86_64") else listOf("x86_64")
    abis.forEach { require(it in abiToTriple) { "Unknown ABI '$it', expected one of ${abiToTriple.keys}" } }
    return abis
}

val repoRootDir: File = rootProject.projectDir.parentFile
val cargoTargetFile: File = File(repoRootDir, "target/android")

// uniffi_bindgen's askama derive fails when cargo's sources are reached through the /home symlink,
// so cargo must see the canonical path of CARGO_HOME.
val canonicalCargoHome: String? = System.getenv("CARGO_HOME")?.let { File(it).canonicalPath }

// Everything that can change the Rust build. The consumer key is read by usos-core's build.rs from
// `.env` (an optional input) or from USOS_CONSUMER_KEY/USOS_CONSUMER_SECRET (not tracked here: run
// with --rerun-tasks after changing those).
val rustInputs = fileTree(repoRootDir) {
    include("Cargo.toml", "Cargo.lock", ".env")
    include("crates/*/Cargo.toml", "crates/*/build.rs", "crates/*/uniffi.toml", "crates/*/src/**")
}

/** Local roots to hide in built artifacts, as (path, replacement); both the given and the canonical spelling. */
fun remapRoots(): Map<String, String> {
    val roots = linkedMapOf<String, String>()
    fun add(path: String?, to: String) {
        if (path.isNullOrBlank()) return
        roots[path] = to
        roots[File(path).canonicalPath] = to
    }
    add(repoRootDir.absolutePath, "/libreusos")
    add(System.getenv("CARGO_HOME"), "/cargo")
    add(System.getenv("RUSTUP_HOME"), "/rustup")
    return roots
}

/** rustc flags, for the Rust sources. */
fun remapFlags(): String = remapRoots().entries.joinToString(" ") { "--remap-path-prefix=${it.key}=${it.value}" }

/** C compiler flags, for the C sources of crates such as aws-lc-sys (picked up by the `cc` crate). */
fun remapCFlags(): String = remapRoots().entries.joinToString(" ") { "-ffile-prefix-map=${it.key}=${it.value}" }

abstract class CargoNdkTask @Inject constructor(private val exec: ExecOperations) : DefaultTask() {
    @get:Input abstract val abis: ListProperty<String>
    @get:Input abstract val platform: Property<Int>
    @get:Input abstract val release: Property<Boolean>
    @get:Input abstract val rustFlags: Property<String>
    @get:Input abstract val cFlags: Property<String>
    @get:Input abstract val ndkPath: Property<String>
    @get:Input @get:Optional abstract val cargoHome: Property<String>
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val rustSources: ConfigurableFileCollection
    @get:Internal abstract val repoRoot: DirectoryProperty
    @get:Internal abstract val cargoTargetDir: DirectoryProperty
    @get:OutputDirectory abstract val jniLibsDir: DirectoryProperty

    @TaskAction
    fun run() {
        val out = jniLibsDir.get().asFile
        out.mkdirs()
        // Drop ABIs that are no longer requested; the wanted ones are replaced by cargo-ndk.
        out.listFiles()?.filter { it.isDirectory && it.name !in abis.get() }?.forEach { it.deleteRecursively() }

        val ndk = File(ndkPath.get())
        val args = mutableListOf("cargo", "ndk")
        abis.get().forEach { args += listOf("-t", it) }
        args += listOf("-P", platform.get().toString(), "-o", out.absolutePath, "build")
        if (release.get()) args += "--release"
        args += listOf("--locked", "-p", "usos-ffi")
        exec.exec {
            workingDir = repoRoot.get().asFile
            commandLine(args)
            environment("CARGO_TARGET_DIR", cargoTargetDir.get().asFile.absolutePath)
            environment("ANDROID_NDK_HOME", ndk.absolutePath)
            environment("RUSTFLAGS", rustFlags.get())
            environment("CFLAGS", cFlags.get())
            // Disk is tight: no incremental caches.
            environment("CARGO_INCREMENTAL", "0")
            cargoHome.orNull?.let { environment("CARGO_HOME", it) }
        }

        // The debug .so carries about 100 MB of DWARF; the copy that goes into the APK does not need it.
        // The unstripped original stays in the cargo target dir (uniffi-bindgen reads that one).
        val strip = File(ndk, "toolchains/llvm/prebuilt/${hostTag()}/bin/llvm-strip")
        check(strip.canExecute()) { "llvm-strip not found at $strip: is the NDK complete?" }
        val libs = out.walkTopDown().filter { it.extension == "so" }.toList()
        check(libs.isNotEmpty()) { "cargo-ndk produced no .so under $out" }
        libs.forEach { so -> exec.exec { commandLine(strip.absolutePath, "--strip-debug", so.absolutePath) } }
    }

    private fun hostTag(): String {
        val os = System.getProperty("os.name").lowercase()
        return when {
            "linux" in os -> "linux-x86_64"
            "mac" in os -> "darwin-x86_64"
            "windows" in os -> "windows-x86_64"
            else -> error("Unsupported host OS: $os")
        }
    }
}

/**
 * The bindings are the same for every ABI and profile (they only describe the API), so the
 * library of the first ABI of the variant is enough. Library mode needs the unstripped cdylib
 * that cargo-ndk left in the cargo target dir.
 */
abstract class UniffiBindgenTask @Inject constructor(private val exec: ExecOperations) : DefaultTask() {
    @get:Input abstract val triple: Property<String>
    @get:Input abstract val release: Property<Boolean>
    @get:Input @get:Optional abstract val cargoHome: Property<String>
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val rustSources: ConfigurableFileCollection
    @get:Internal abstract val repoRoot: DirectoryProperty
    @get:Internal abstract val cargoTargetDir: DirectoryProperty
    @get:OutputDirectory abstract val outDir: DirectoryProperty

    @TaskAction
    fun run() {
        val out = outDir.get().asFile
        out.mkdirs()
        // Remove stale generated files; the directory itself stays.
        out.listFiles()?.forEach { it.deleteRecursively() }
        val profile = if (release.get()) "release" else "debug"
        val lib = File(cargoTargetDir.get().asFile, "${triple.get()}/$profile/libusos_ffi.so")
        require(lib.isFile) { "Missing $lib: run the buildRustLibs task of this variant first" }
        exec.exec {
            workingDir = repoRoot.get().asFile
            commandLine(
                "cargo", "run", "--locked", "-p", "usos-ffi", "--features", "bindgen-cli", "--bin", "uniffi-bindgen", "--",
                "generate", "--library", lib.absolutePath, "--language", "kotlin", "--out-dir", out.absolutePath,
            )
            environment("CARGO_TARGET_DIR", cargoTargetDir.get().asFile.absolutePath)
            // Disk is tight: no incremental caches, and (host tool only) no debug info.
            environment("CARGO_INCREMENTAL", "0")
            environment("CARGO_PROFILE_DEV_DEBUG", "0")
            cargoHome.orNull?.let { environment("CARGO_HOME", it) }
        }
    }
}

android {
    namespace = "io.github.voxix.libreusos"
    compileSdk = 36
    ndkVersion = pinnedNdkVersion

    defaultConfig {
        applicationId = "io.github.voxix.libreusos"
        minSdk = minSdkVersion
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"
    }

    // Release signing comes from the environment (own repo / IzzyOnDroid CI); without it the APK stays unsigned.
    val releaseKeystore = System.getenv("LIBREUSOS_KEYSTORE")?.takeIf { it.isNotBlank() }
    if (releaseKeystore != null) {
        signingConfigs {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = System.getenv("LIBREUSOS_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("LIBREUSOS_KEY_ALIAS")
                keyPassword = System.getenv("LIBREUSOS_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            if (releaseKeystore != null) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    // F-Droid: no dependency metadata blob in the APK.
    dependenciesInfo {
        includeInApk = false
        includeInBundle = false
    }
}

androidComponents {
    onVariants { variant: ApplicationVariant ->
        val release = variant.buildType == "release"
        val suffix = variant.name.replaceFirstChar { it.uppercase() }
        val abis = abisFor(release)

        val buildRustLibs = tasks.register<CargoNdkTask>("buildRustLibs$suffix") {
            group = "rust"
            description = "Builds usos-ffi for the ${variant.name} variant with cargo-ndk"
            this.abis.set(abis)
            platform.set(variant.minSdk.apiLevel)
            this.release.set(release)
            rustFlags.set(remapFlags())
            cFlags.set(remapCFlags())
            ndkPath.set(androidComponents.sdkComponents.ndkDirectory.map { it.asFile.absolutePath })
            canonicalCargoHome?.let { cargoHome.set(it) }
            rustSources.from(rustInputs)
            repoRoot.set(repoRootDir)
            cargoTargetDir.set(cargoTargetFile)
            jniLibsDir.set(layout.buildDirectory.dir("generated/rust/${variant.name}/jniLibs"))
        }

        val generateBindings = tasks.register<UniffiBindgenTask>("generateUniffiBindings$suffix") {
            group = "rust"
            description = "Generates the Kotlin bindings of usos-ffi (${variant.name}) with uniffi-bindgen"
            dependsOn(buildRustLibs)
            triple.set(abiToTriple.getValue(abis.first()))
            this.release.set(release)
            canonicalCargoHome?.let { cargoHome.set(it) }
            rustSources.from(rustInputs)
            repoRoot.set(repoRootDir)
            cargoTargetDir.set(cargoTargetFile)
            outDir.set(layout.buildDirectory.dir("generated/rust/${variant.name}/kotlin"))
        }

        variant.sources.jniLibs?.addGeneratedSourceDirectory(buildRustLibs, CargoNdkTask::jniLibsDir)
        variant.sources.kotlin?.addGeneratedSourceDirectory(generateBindings, UniffiBindgenTask::outDir)
    }
}

